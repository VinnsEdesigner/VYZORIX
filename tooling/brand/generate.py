#!/usr/bin/env python3
"""Generate every Vyzorix brand asset from the traced ORBITAL V mark.

`source/orbital-v.svg` is the master: the mark as traced from the supplied
artwork. Everything else — the icon, the mono icon, the Safari mask silhouette,
the wordmark, and the raster favicons — is derived from it here, so the assets
cannot drift apart the way hand-maintained files do.

Run from the repo root with the venv that has cairosvg + Pillow + fontTools:
    /workspace/vision-venv/bin/python tooling/brand/generate.py
"""
import io
import os
import re

import cairosvg
from fontTools.misc.transform import Transform
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'source', 'orbital-v.svg')
BRAND_DIR = os.path.join('apps', 'VyzoriX_web', 'public', 'brand')
FONT_CANDIDATES = [
    '/workspace/mega-webclient-ref/fonts/Inter-SemiBold.ttf',
    os.path.join(HERE, 'Inter-SemiBold.ttf'),
]

# The brand accent is rose-700. The artwork arrived red (#f71c4a); the app's
# theme is rose, so the mark is recoloured to match rather than carrying two
# reds that are nearly — but not quite — the same.
ACCENT = '#be123c'          # rose-700
ARM_DARK = '#ffffff'        # the left arm on a dark surface
ARM_LIGHT = '#171717'       # the left arm on a light surface (the app's dark ink)
CANVAS = '#0d0d0d'          # the console's canvas colour

WORD = 'Vyzorix'
WORD_CAP_PX = 17.0
WORD_GAP = 10.0
WORD_DARK = '#e5e5e5'       # wordmark colour on a dark surface
WORD_LIGHT = '#171717'      # wordmark colour on a light surface


# ---------------------------------------------------------------------------
# The mark, read from the traced source.
# ---------------------------------------------------------------------------

def read_source():
    """Return (white_paths, accent_paths, viewbox, transform) from the master."""
    svg = open(SOURCE).read()
    viewbox = re.search(r'viewBox="([^"]+)"', svg).group(1)
    transform = re.search(r'<g transform="([^"]+)"', svg).group(1)
    # The source groups white paths first, then the accent ones, each in its own
    # `<g fill=...>`; keep that split so each layer can be recoloured.
    groups = re.findall(r'<g fill="(#[0-9a-fA-F]{6})">(.*?)</g>', svg, re.S)
    white, accent = [], []
    for fill, body in groups:
        paths = re.findall(r'<path d="([^"]+)"', body)
        if fill.lower() == '#ffffff':
            white.extend(paths)
        else:
            accent.extend(paths)
    return white, accent, viewbox, transform


WHITE_PATHS, ACCENT_PATHS, SOURCE_VIEWBOX, SOURCE_TRANSFORM = read_source()


def _layer(paths, fill, cls=None):
    attr = f' class="{cls}"' if cls else ''
    body = '\n'.join(f'      <path d="{d}"/>' for d in paths)
    return f'    <g{attr} fill="{fill}">\n{body}\n    </g>'


def mark_group(accent=ACCENT, arm=ARM_DARK, arm_class=None):
    """The mark's two layers, for any SVG sharing the source viewBox."""
    return '\n'.join([_layer(WHITE_PATHS, arm, arm_class), _layer(ACCENT_PATHS, accent)])


def icon_adaptive_svg(accent=ACCENT) -> str:
    """The mark whose left arm follows the surface it is shown on.

    The left arm is white in the artwork, which vanishes against a light browser
    chrome (the tab strip and bookmarks bar are light by default). A
    `prefers-color-scheme` rule inside the SVG flips the arm to the app's dark ink
    on a light surface, so one file reads correctly in both. The rule is part of
    the SVG itself rather than the page, because a favicon and an `<img>`-loaded
    SVG are their own document and cannot be reached by the page's CSS.
    """
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  Vyzorix app mark — ORBITAL V.

  The left arm follows the surface: white on a dark surface, dark ink on a light
  one. Generated by tooling/brand/generate.py from source/orbital-v.svg; edit the
  source or the generator, not this file.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{SOURCE_VIEWBOX}" role="img" aria-label="Vyzorix">
  <style>
    .vyz-arm {{ fill: {ARM_DARK}; }}
    @media (prefers-color-scheme: light) {{ .vyz-arm {{ fill: {ARM_LIGHT}; }} }}
  </style>
  <g transform="{SOURCE_TRANSFORM}">
{mark_group(accent, arm_class='vyz-arm')}
  </g>
</svg>
'''


def icon_svg(accent=ACCENT, arm=ARM_LIGHT) -> str:
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  Vyzorix app mark — ORBITAL V.

  A "V" (left arm, right arm accent) with an orbital arc sweeping over the top
  right. The arm is the dark ink so the mark reads on the light browser chrome a
  favicon is shown against. Generated by tooling/brand/generate.py from
  source/orbital-v.svg; edit the source or the generator, not this file.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{SOURCE_VIEWBOX}" role="img" aria-label="Vyzorix">
  <g transform="{SOURCE_TRANSFORM}">
{mark_group(accent, arm)}
  </g>
</svg>
'''


def mask_icon_svg() -> str:
    """A flat silhouette for Safari pinned tabs, which tints the shape itself."""
    body = '\n'.join(f'    <path d="{d}"/>' for d in WHITE_PATHS + ACCENT_PATHS)
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  Vyzorix mask icon — the ORBITAL V as a flat silhouette for Safari pinned tabs.
  Safari tints it with the link's color attribute. Generated by
  tooling/brand/generate.py.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{SOURCE_VIEWBOX}" role="img" aria-label="Vyzorix">
  <g transform="{SOURCE_TRANSFORM}" fill="#000000">
{body}
  </g>
</svg>
'''


# ---------------------------------------------------------------------------
# Wordmark: the mark beside the word, from real Inter outlines.
# ---------------------------------------------------------------------------

def find_font() -> str:
    for path in FONT_CANDIDATES:
        if os.path.exists(path):
            return path
    raise SystemExit('Inter-SemiBold.ttf not found')


def word_outline(font: TTFont, word: str):
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font['hmtx']
    x = 0.0
    parts = []
    for ch in word:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, Transform(1, 0, 0, -1, x, 0)))
        d = pen.getCommands()
        if d:
            parts.append(d)
        x += hmtx[name][0]
    cap = getattr(font['OS/2'], 'sCapHeight', font['head'].unitsPerEm)
    return ' '.join(parts), x, cap


def source_size():
    _, _, w, h = (float(v) for v in SOURCE_VIEWBOX.split())
    return w, h


def wordmark_svg(path_d, advance, cap, word_fill, surface, arm=ARM_DARK) -> str:
    mark_w, mark_h = source_size()
    scale = WORD_CAP_PX / cap
    text_w = advance * scale
    total_w = mark_w + WORD_GAP + text_w
    total_h = mark_h
    baseline = (total_h + WORD_CAP_PX) / 2
    text_x = mark_w + WORD_GAP

    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  Vyzorix wordmark, for {surface} surfaces.

  The ORBITAL V beside the word. Letterforms are real Inter outlines, laid out
  with the font's own advance widths and cap height, so the wordmark matches the
  interface typeface. Generated by tooling/brand/generate.py. Inter is under the
  SIL Open Font License 1.1.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total_w:.2f} {total_h:.2f}" role="img" aria-label="Vyzorix">
  <g transform="{SOURCE_TRANSFORM}">
{mark_group(arm=arm)}
  </g>
  <g transform="translate({text_x:.2f} {baseline:.2f}) scale({scale:.6f})">
    <path d="{path_d}" fill="{word_fill}"/>
  </g>
</svg>
'''


# ---------------------------------------------------------------------------
# Raster assets: rasterise the same SVG, so pixels and vectors cannot disagree.
# ---------------------------------------------------------------------------

def raster_icon(size: int, background: str | None = None) -> Image.Image:
    """Rasterise the icon at `size`.

    Renders `icon_svg()` (the dark-ink arm), not the white-arm source: a raster
    cannot carry the SVG's prefers-color-scheme rule, and the browser chrome a
    favicon sits on is light.
    """
    png = cairosvg.svg2png(
        bytestring=icon_svg().encode(), output_width=size, output_height=size,
        background_color=background,
    )
    return Image.open(io.BytesIO(png)).convert('RGBA')


def main() -> None:
    os.makedirs(BRAND_DIR, exist_ok=True)

    writes = {
        # The favicon: the dark arm unconditionally, because a favicon cannot use
        # prefers-color-scheme and sits on light browser chrome.
        'vyzorix_icon_dark.svg': icon_svg(),
        # Surface-matched marks for in-app use, where the surface colour is known
        # from the theme. Mirrors the wordmark's dark/light pair.
        'vyzorix_icon_on_dark.svg': icon_svg(arm=ARM_DARK),
        'vyzorix_icon_on_light.svg': icon_svg(arm=ARM_LIGHT),
        'vyzorix_icon_adaptive.svg': icon_adaptive_svg(),
        'vyzorix_mask_icon.svg': mask_icon_svg(),
    }

    font = TTFont(find_font())
    path_d, advance, cap = word_outline(font, WORD)
    writes['vyzorix_wordmark_dark.svg'] = wordmark_svg(path_d, advance, cap, WORD_DARK, 'dark', ARM_DARK)
    writes['vyzorix_wordmark_light.svg'] = wordmark_svg(path_d, advance, cap, WORD_LIGHT, 'light', ARM_LIGHT)

    for name, content in writes.items():
        with open(os.path.join(BRAND_DIR, name), 'w') as fh:
            fh.write(content)
        print('wrote', name)

    # Rasters. A PNG cannot carry a prefers-color-scheme rule, and a favicon sits
    # on the browser's own light chrome, so the arm is baked as the dark ink and
    # the canvas is left transparent: the tab strip supplies the background.
    transparent = None
    raster_icon(64, transparent).save(os.path.join(BRAND_DIR, 'favicon.ico'), sizes=[(16, 16), (32, 32), (48, 48)])
    raster_icon(32, transparent).save(os.path.join(BRAND_DIR, 'favicon-32.png'))
    raster_icon(16, transparent).save(os.path.join(BRAND_DIR, 'favicon-16.png'))

    canvas_rgb = tuple(int(CANVAS[i:i + 2], 16) for i in (1, 3, 5))
    touch = Image.new('RGB', (180, 180), canvas_rgb)
    touch.paste(raster_icon(180, CANVAS), (0, 0))
    touch.save(os.path.join(BRAND_DIR, 'apple-touch-icon.png'))
    print('wrote favicon.ico, favicon-16.png, favicon-32.png, apple-touch-icon.png')


if __name__ == '__main__':
    main()
