#!/usr/bin/env python3
"""Generate the Vyzorix app-open animations from the traced mark.

Two animations, matching the two supplied GIFs:

  assemble — the V's arms draw in, then the orbit arc arrives.  (GIF A, 9f)
  orbit    — the arc sweeps a full turn around the static V.    (GIF B, 16f)

Both are generated from the same paths as the icon, so the animation and the
logo cannot drift apart.

SMIL (`animate` / `animateTransform`) is used rather than CSS keyframes, for two
reasons: it works inside an `<img>`, where the SVG is its own document and the
page's stylesheet does not reach it; and its rotation takes an explicit centre in
user-space, avoiding the `transform-origin` / `transform-box` differences between
browsers. `prefers-reduced-motion` cannot be honoured inside an `<img>`, so the
consumer decides — the app renders a still mark instead when motion is reduced.

Run from the repo root:
    /workspace/vision-venv/bin/python tooling/brand/animations.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'source', 'orbital-v.svg')
BRAND_DIR = os.path.join('apps', 'VyzoriX_web', 'public', 'brand')

ACCENT = '#be123c'   # rose-700, matching the icon
WHITE = '#ffffff'

# Timings, taken from the source GIFs.
ASSEMBLE_MS = 9 * 180      # 1620 ms
ORBIT_MS = 16 * 110        # 1760 ms

# The arc sweeps about the combined centre of the mark, in viewBox units.
ORBIT_CENTRE = (160.0, 115.5)


def read_paths():
    """Return (v_paths, arc_paths, viewbox, transform) from the traced master.

    The V is the two long arms; the arc is the two shorter shapes in the
    top-right. They are told apart by path length: the arms are far longer.
    """
    svg = open(SOURCE).read()
    viewbox = re.search(r'viewBox="([^"]+)"', svg).group(1)
    transform = re.search(r'<g transform="([^"]+)"', svg).group(1)

    entries = []
    for fill, body in re.findall(r'<g fill="(#[0-9a-fA-F]{6})">(.*?)</g>', svg, re.S):
        for d in re.findall(r'<path d="([^"]+)"', body):
            entries.append((fill, d))

    entries.sort(key=lambda e: len(e[1]), reverse=True)
    return entries[:2], entries[2:], viewbox, transform


def split_by_fill(paths):
    white = [p for p in paths if p[0].lower() == '#ffffff']
    accent = [p for p in paths if p[0].lower() != '#ffffff']
    return white, accent


def paths_block(paths, indent):
    pad = ' ' * indent
    return '\n'.join(f'{pad}<path d="{d}"/>' for _, d in paths)


def assemble_svg(v_paths, arc_paths, viewbox, transform) -> str:
    """The V draws in, then the arc arrives."""
    v_white, v_accent = split_by_fill(v_paths)
    arc_white, arc_accent = split_by_fill(arc_paths)

    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  Vyzorix — app-open animation: ASSEMBLE.

  The V's two arms fade and rise in, then the orbit arc arrives and settles.
  Generated by tooling/brand/animations.py from source/orbital-v.svg.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" role="img" aria-label="Vyzorix">
  <g transform="{transform}">
    <g fill="{WHITE}" opacity="0">
      <animate attributeName="opacity" from="0" to="1" begin="0ms" dur="420ms" fill="freeze"/>
      <animateTransform attributeName="transform" type="translate" from="0 6" to="0 0" begin="0ms" dur="420ms" fill="freeze"/>
{paths_block(v_white, 6)}
    </g>
    <g fill="{ACCENT}" opacity="0">
      <animate attributeName="opacity" from="0" to="1" begin="180ms" dur="420ms" fill="freeze"/>
      <animateTransform attributeName="transform" type="translate" from="0 6" to="0 0" begin="180ms" dur="420ms" fill="freeze"/>
{paths_block(v_accent, 6)}
    </g>
    <g fill="{WHITE}" opacity="0">
      <animate attributeName="opacity" from="0" to="1" begin="620ms" dur="560ms" fill="freeze"/>
{paths_block(arc_white, 6)}
    </g>
    <g fill="{ACCENT}" opacity="0">
      <animate attributeName="opacity" from="0" to="1" begin="760ms" dur="560ms" fill="freeze"/>
{paths_block(arc_accent, 6)}
    </g>
  </g>
</svg>
'''


def orbit_svg(v_paths, arc_paths, viewbox, transform) -> str:
    """The arc sweeps a full turn around the static V."""
    v_white, v_accent = split_by_fill(v_paths)
    arc_white, arc_accent = split_by_fill(arc_paths)
    cx, cy = ORBIT_CENTRE

    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  Vyzorix — app-open animation: ORBIT.

  The V holds still while the orbit arc sweeps a full turn around it. Generated
  by tooling/brand/animations.py from source/orbital-v.svg.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" role="img" aria-label="Vyzorix">
  <g transform="{transform}">
    <g fill="{WHITE}">
{paths_block(v_white, 6)}
    </g>
    <g fill="{ACCENT}">
{paths_block(v_accent, 6)}
    </g>
  </g>
  <g transform="rotate(0 {cx} {cy})">
    <animateTransform attributeName="transform" type="rotate"
      from="0 {cx} {cy}" to="360 {cx} {cy}" dur="{ORBIT_MS}ms" repeatCount="indefinite"/>
    <g transform="{transform}">
      <g fill="{WHITE}">
{paths_block(arc_white, 8)}
      </g>
      <g fill="{ACCENT}">
{paths_block(arc_accent, 8)}
      </g>
    </g>
  </g>
</svg>
'''


def main() -> None:
    v_paths, arc_paths, viewbox, transform = read_paths()
    os.makedirs(BRAND_DIR, exist_ok=True)

    writes = {
        'vyzorix_boot_assemble.svg': assemble_svg(v_paths, arc_paths, viewbox, transform),
        'vyzorix_boot_orbit.svg': orbit_svg(v_paths, arc_paths, viewbox, transform),
    }
    for name, content in writes.items():
        with open(os.path.join(BRAND_DIR, name), 'w') as fh:
            fh.write(content)
        print('wrote', name)


if __name__ == '__main__':
    main()
