package device

import (
	"context"
	"errors"
	"fmt"
	"strings"
	"time"

	libv "github.com/VinnsEdesigner/libv/go"
	"github.com/VinnsEdesigner/vyzorix/apps/api/internal/domain/deployconfig"
	"github.com/VinnsEdesigner/vyzorix/apps/api/internal/infrastructure/configscan"
)

// ConfigKind is the server-signature domain for a device config. Distinct from
// commands and connects, so a config signature cannot be replayed as anything else.
const ConfigKind = "config"

// DeviceConfig is the resolved settings a device receives once it is claimed.
//
// It is settings only. A config must never carry a key, a token or a password:
// the whole point of the keypair model is that nothing secret is transmitted, and
// a secret in the config would reintroduce exactly that. BuildConfig enforces it.
// Field order is deliberate: pointer-bearing fields first so the GC scans a
// shorter region. fieldalignment enforces it.
type DeviceConfig struct {
	DeviceID                string
	OrganizationID          string
	Name                    string
	StreamPath              string
	Version                 int
	TierCap                 int
	TelemetryIntervalSecond int
	TerminalEnabled         bool
	USBEnabled              bool
	AppsEnabled             bool
}

// DefaultTelemetryIntervalSeconds is how often a device reports by default.
const DefaultTelemetryIntervalSeconds = 60

// BuildConfig assembles the config for a claimed device.
//
// It reads only what the device record actually holds. Fields the record does not
// carry (per-feature flags, a telemetry interval) come from the defaults above
// rather than from a settings table that does not exist yet — inventing a lookup
// would be worse than a documented default.
func (s *Service) BuildConfig(ctx context.Context, deviceID string) (*DeviceConfig, error) {
	d, err := s.deviceRepo.FindByID(ctx, deviceID)
	if err != nil {
		return nil, err
	}

	if d.OrganizationID == "" {
		return nil, fmt.Errorf("%w: device %s has no organization", ErrDeviceNotFound, deviceID)
	}

	return &DeviceConfig{
		Version:                 1,
		DeviceID:                d.ID,
		OrganizationID:          d.OrganizationID,
		Name:                    d.DeviceName,
		TierCap:                 int(d.Tier),
		TelemetryIntervalSecond: DefaultTelemetryIntervalSeconds,
		TerminalEnabled:         true,
		USBEnabled:              false,
		AppsEnabled:             true,
		StreamPath:              "/v1/device/" + d.ID + "/stream",
	}, nil
}

// SignDocument signs a rendered document. It is a function rather than a
// libv.Signer so the server has exactly one signing key: passing a second
// signer type here would let the config and the command frames be signed by
// different keys, which the device would see as one of them failing to verify.
type SignDocument func(document string) (string, error)

// RenderConfig renders a config as a signed vyzorix.v document.
//
// The document is written in the format's own shape so libv parses it: depth is
// the count of leading v characters, and the signature is the last line.
func RenderConfig(sign SignDocument, cfg DeviceConfig) (string, error) {
	var b strings.Builder

	b.WriteString("' vyzorix.v - device configuration\n")
	b.WriteString("' Generated by the server. Signed; a tampered field fails verification.\n")

	// Depth 1: the device identity.
	fmt.Fprintf(&b, "v device %s\n", cfg.DeviceID)
	fmt.Fprintf(&b, "vv org %s\n", cfg.OrganizationID)
	if cfg.Name != "" {
		fmt.Fprintf(&b, "vv name %s\n", cfg.Name)
	}
	fmt.Fprintf(&b, "vv tier %d\n", cfg.TierCap)

	// Depth 2 under a cloud section: where to connect and how often to report.
	b.WriteString("vv cloud\n")
	fmt.Fprintf(&b, "vvv stream %s\n", cfg.StreamPath)
	fmt.Fprintf(&b, "vvv hb %ds\n", cfg.TelemetryIntervalSecond)
	b.WriteString("vvv backoff 1s>30s\n")

	// Feature flags. Only the enabled ones are written, so the document says what
	// the device may do rather than what it may not.
	b.WriteString("vv features\n")
	fmt.Fprintf(&b, "vvv terminal %t\n", cfg.TerminalEnabled)
	fmt.Fprintf(&b, "vvv usb %t\n", cfg.USBEnabled)
	fmt.Fprintf(&b, "vvv apps %t\n", cfg.AppsEnabled)

	fmt.Fprintf(&b, "v version %d\n", cfg.Version)

	return sign(b.String())
}

// ValidateConfigHasNoSecrets refuses a config that carries a secret value.
//
// It delegates to the structural walk in configscan, which is the one check
// both config paths use. The earlier implementation here scanned every line for
// the words secret, token, key and hmac, which refuses the schema's own
// `secret NAME` nodes — the field that exists so a config can name a secret
// without carrying one — so it would reject any config carrying apps.
func ValidateConfigHasNoSecrets(document string) error {
	return configscan.Scan(document)
}

// ConfigEnvelope is what the device receives: the signed document and the
// signature metadata it needs to verify it. The signature is inside the document,
// so this carries only the version, for the re-fetch decision.
type ConfigEnvelope struct {
	Document string
	DeviceID string
	Version  int
	IssuedAt int64
}

// ConfigForDevice builds, validates and renders a device's config in one call.
//
// The validation is not optional: every caller gets a config that has been checked
// for secrets, so the invariant holds by construction rather than by each caller
// remembering.
//
// A device that has been deployed to is served the config the deploy stored —
// the exact bytes the user's manifest produced and the server signed, at the
// version it was signed with. The registration config below is the fallback for a
// device that has never been deployed to; it is not a second source of truth for
// one that has.
func (s *Service) ConfigForDevice(
	ctx context.Context,
	sign SignDocument,
	deviceID string,
) (*ConfigEnvelope, error) {
	if s.deployConfigs != nil {
		deployed, err := s.deployConfigs.Current(ctx, deviceID)
		if err != nil && !errors.Is(err, deployconfig.ErrNotFound) {
			return nil, err
		}

		if deployed != nil {
			return &ConfigEnvelope{
				Version:  deployed.Version,
				Document: deployed.Document,
				IssuedAt: deployed.CreatedAt.UnixMilli(),
				DeviceID: deviceID,
			}, nil
		}
	}

	if sign == nil {
		return nil, fmt.Errorf("no signing key configured; cannot issue a signed config")
	}

	cfg, err := s.BuildConfig(ctx, deviceID)
	if err != nil {
		return nil, err
	}

	document, err := RenderConfig(sign, *cfg)
	if err != nil {
		return nil, err
	}

	// Parse the document with the format's own parser before signing it. A
	// malformed document that reached a device would fail there, where it is far
	// harder to diagnose; refusing it here means the server never issues one.
	if _, err := libv.Parse(document); err != nil {
		return nil, fmt.Errorf("rendered config does not parse: %w", err)
	}

	if err := ValidateConfigHasNoSecrets(document); err != nil {
		return nil, err
	}

	return &ConfigEnvelope{
		Version:  cfg.Version,
		Document: document,
		IssuedAt: time.Now().UnixMilli(),
		DeviceID: cfg.DeviceID,
	}, nil
}

// DeployConfigSource is the deploy store's read side: the signed config a device
// was deployed to. It is the narrow read this package needs, so the delivery path
// does not depend on the deploy feature's write side.
//
// *storage.DeployConfigRepository satisfies it. It is an interface so a test can
// supply a store without a database.
type DeployConfigSource interface {
	// Current returns the config the device should be running, or
	// deployconfig.ErrNotFound when it has never been deployed to.
	Current(ctx context.Context, deviceID string) (*deployconfig.Record, error)
}

// SetDeployConfigSource wires the deploy store the delivery path reads. Without
// it, a device is served only the registration config, which is the pre-deploy
// behaviour.
func (s *Service) SetDeployConfigSource(source DeployConfigSource) {
	s.deployConfigs = source
}
