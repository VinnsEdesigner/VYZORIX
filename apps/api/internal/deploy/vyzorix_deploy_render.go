package deploy

import (
	"fmt"
	"sort"
	"strings"
)

// The vyzorix.v renderer. Output is byte-identical for the same input: apps keep
// manifest order, env keys are sorted, every other field is written in a fixed
// order (§5.1).

const (
	// appsContainerDepth holds the `apps` node; app nodes sit one deeper.
	appsContainerDepth = 2
	// appFieldDepth holds an app's own fields.
	appFieldDepth = 4
	// artifactFieldDepth holds an artifact's fields.
	artifactFieldDepth = 5
)

// renderer accumulates lines and the first token error, so a bad value aborts
// the render rather than producing a partial document.
type renderer struct {
	err   error
	lines []string
}

// node writes one node at the given depth.
func (r *renderer) node(depth int, key string, values ...string) {
	if r.err != nil {
		return
	}

	line := strings.Repeat("v", depth) + " " + key

	for _, value := range values {
		tok, err := token(value)
		if err != nil {
			r.err = err

			return
		}

		line += " " + tok
	}

	r.lines = append(r.lines, line)
}

// RenderConfig writes the unsigned vyzorix.v document. It never signs, so a
// render can be inspected without a key.
func RenderConfig(cfg Config) (string, error) {
	r := &renderer{lines: make([]string, 0, 16+len(cfg.Apps)*8)}

	r.lines = append(r.lines,
		"' vyzorix.v - device configuration",
		"' Generated by the server. Signed; a tampered field fails verification.",
	)

	r.node(1, "device", cfg.DeviceID)
	r.node(2, "org", cfg.OrgID)

	if cfg.Name != "" {
		r.node(2, "name", cfg.Name)
	}

	r.node(2, "tier", fmt.Sprintf("%d", cfg.TierCap))
	r.node(2, "member", cfg.MemberID)

	r.node(2, "cloud")
	r.node(3, "stream", cfg.StreamPath)
	r.node(3, "hb", fmt.Sprintf("%ds", cfg.HeartbeatSeconds))
	r.node(3, "backoff", "1s>30s")

	r.node(2, "features")
	r.node(3, "terminal", fmt.Sprintf("%t", cfg.TerminalEnabled))
	r.node(3, "usb", fmt.Sprintf("%t", cfg.USBEnabled))
	r.node(3, "apps", "true")

	r.node(appsContainerDepth, "apps")

	for i := range cfg.Apps {
		r.renderApp(&cfg.Apps[i])
	}

	r.node(1, "version", fmt.Sprintf("%d", cfg.Version))

	if r.err != nil {
		return "", r.err
	}

	return strings.Join(r.lines, "\n") + "\n", nil
}

// renderApp writes one app node and its children.
func (r *renderer) renderApp(app *AppConfig) {
	r.node(appsContainerDepth+1, "app", app.Name)
	r.node(appFieldDepth, "dir", "/home/apps/"+app.Name)
	r.node(appFieldDepth, "cmd", app.Cmd)
	r.node(appFieldDepth, "port", fmt.Sprintf("%d", app.Port))
	r.node(appFieldDepth, "autostart", fmt.Sprintf("%t", app.Autostart))
	r.node(appFieldDepth, "expose", string(app.Expose))
	r.node(appFieldDepth, "purge", fmt.Sprintf("%t", app.Purge))

	r.renderEnv(app)
	r.renderSecrets(app)

	for i := range app.Artifacts {
		r.renderArtifact(&app.Artifacts[i])
	}

	r.renderPWA(app)
}

// renderEnv writes one `env KEY=VALUE` node per variable, keys sorted.
func (r *renderer) renderEnv(app *AppConfig) {
	if len(app.Env) == 0 {
		return
	}

	keys := make([]string, 0, len(app.Env))
	for key := range app.Env {
		keys = append(keys, key)
	}

	sort.Strings(keys)

	for _, key := range keys {
		r.node(appFieldDepth, "env", key+"="+app.Env[key])
	}
}

// renderSecrets writes one `secret NAME` node per name; values travel on their
// own channel (§9b).
func (r *renderer) renderSecrets(app *AppConfig) {
	for _, name := range app.Secrets {
		r.node(appFieldDepth, "secret", name)
	}
}

// renderArtifact writes one artifact node and its fields.
func (r *renderer) renderArtifact(art *ArtifactConfig) {
	r.node(appFieldDepth, "artifact", art.Name)

	if art.Arch != "" {
		r.node(artifactFieldDepth, "arch", art.Arch)
	}

	r.node(artifactFieldDepth, "url", art.URL)
	r.node(artifactFieldDepth, "sha256", art.SHA256)
	r.node(artifactFieldDepth, "kind", string(art.Kind))

	if art.Size > 0 {
		r.node(artifactFieldDepth, "size", fmt.Sprintf("%d", art.Size))
	}
}

// renderPWA writes the pwa node only when the webroot is a PWA. Absent and
// false produce no node at all, which is the negative case (§6).
func (r *renderer) renderPWA(app *AppConfig) {
	if app.PWA == nil || !app.PWA.Enabled {
		return
	}

	r.node(appFieldDepth, "pwa", "true")

	// Only fields that override a default are written, so the document does not
	// restate a value the generator would have chosen anyway.
	overrides := []struct{ key, value string }{
		{"name", app.PWA.Name},
		{"short_name", app.PWA.ShortName},
		{"description", app.PWA.Description},
		{"theme_color", app.PWA.ThemeColor},
		{"background_color", app.PWA.BackgroundColor},
		{"display", app.PWA.Display},
		{"orientation", app.PWA.Orientation},
		{"start_url", app.PWA.StartURL},
	}

	for _, o := range overrides {
		if o.value != "" {
			r.node(artifactFieldDepth, o.key, o.value)
		}
	}

	for i := range app.PWA.Icons {
		icon := &app.PWA.Icons[i]
		r.node(artifactFieldDepth, "icon", icon.Src, icon.Sizes, icon.Type)
	}
}

// token renders one value as a libv token. The format splits on whitespace and
// quotes with `"`, so a value with a space is quoted and one carrying a quote or
// newline is refused rather than mangled into a different document.
func token(value string) (string, error) {
	if strings.ContainsAny(value, "\"\n\r") {
		return "", fmt.Errorf("deploy: value %q contains a quote or newline, which the vyzorix.v format cannot carry", value)
	}

	if strings.ContainsAny(value, " \t") {
		return "\"" + value + "\"", nil
	}

	return value, nil
}
